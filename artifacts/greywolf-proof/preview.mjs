import fs from 'node:fs/promises';
import {chromium} from 'playwright';
const root=new URL('.',import.meta.url).pathname;
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('file://'+root+'index.html');await page.evaluate(()=>window.proofReady);
await page.evaluate(()=>window.proof.render(9.6));
await page.locator('#film').screenshot({path:root+'film-flag.png'});
await page.evaluate(()=>window.proof.render(16.5));
await page.locator('#film').screenshot({path:root+'film-corrected.png'});
await page.getByRole('button',{name:'Try the numbers yourself'}).click();
await page.screenshot({path:root+'inspect-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Try the wrong period'}).click();
const wrong=await page.evaluate(()=>window.proof.validate());
if(wrong.ok||wrong.difference!==52985)throw Error('Wrong-period interaction failed');
await page.getByRole('button',{name:'Show source for Services: 80,408'}).click();
if(await page.locator('#source-highlight').isHidden())throw Error('Source link did not highlight');
await page.screenshot({path:root+'inspect-seeded.png',fullPage:true});
await page.getByRole('button',{name:'Use the quarter'}).click();
if(!(await page.evaluate(()=>window.proof.validate())).ok)throw Error('Correction did not restore checks');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:root+'inspect-mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
if(errors.length)throw Error(errors.join('\n'));
await fs.writeFile(root+'browser-checks.json',JSON.stringify({wrongPeriodDifference:wrong.difference,corrected:true,sourceHighlight:true,mobileOverflow:false,pageErrors:errors},null,2));
await browser.close();console.log('Browser interactions and narrow layout passed.');
